#!/usr/bin/env bash
# GameDay installer — Debian/Ubuntu LXC container, VM or bare metal (Proxmox friendly).
#
#   ./install.sh                     # Docker (installed if missing), port 7000
#   ./install.sh --port 8080         # different port
#   ./install.sh --url https://gd.example.com   # behind a reverse proxy
#   ./install.sh --native            # no Docker: Node 22 + systemd service
#   ./install.sh --repo <git-url>    # clone instead of using this checkout
#
# Re-running it is safe: secrets are kept, the app is rebuilt and restarted.
set -euo pipefail

APP="gameday"
PORT=7000
DIR="/opt/gameday"
PUBLIC_URL=""
MODE="auto"
REPO=""
SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31mError: %s\033[0m\n' "$*" >&2; exit 1; }

usage() {
  sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT="${2:?}"; shift 2 ;;
    --url) PUBLIC_URL="${2:?}"; shift 2 ;;
    --dir) DIR="${2:?}"; shift 2 ;;
    --repo) REPO="${2:?}"; shift 2 ;;
    --native) MODE="native"; shift ;;
    --docker) MODE="docker"; shift ;;
    -h|--help) usage ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done
case "$PORT" in ''|*[!0-9]*) die "--port must be a number" ;; esac

SUDO=""
if [ "$(id -u)" -ne 0 ]; then
  command -v sudo >/dev/null 2>&1 || die "run as root (or install sudo)"
  SUDO="sudo"
fi

install_pkgs() {
  if command -v curl >/dev/null && command -v git >/dev/null && command -v openssl >/dev/null; then
    return
  fi
  say "Installing base packages"
  $SUDO apt-get update -qq
  DEBIAN_FRONTEND=noninteractive $SUDO apt-get install -y -qq curl ca-certificates git openssl "$@"
}

checkout_source() {
  if [ -n "$REPO" ]; then
    if [ -d "$DIR/.git" ]; then
      say "Updating $DIR"
      $SUDO git -C "$DIR" pull --ff-only
    else
      say "Cloning $REPO into $DIR"
      $SUDO mkdir -p "$(dirname "$DIR")"
      $SUDO git clone --depth 1 "$REPO" "$DIR"
    fi
  elif [ "$SOURCE_DIR" != "$DIR" ]; then
    say "Copying $SOURCE_DIR to $DIR"
    $SUDO mkdir -p "$DIR"
    $SUDO tar -C "$SOURCE_DIR" --exclude node_modules --exclude data --exclude .git -cf - . | $SUDO tar -C "$DIR" -xf -
  fi
  [ -f "$DIR/package.json" ] || die "$DIR does not look like a GameDay checkout"
}

write_env() {
  ENV_FILE="$DIR/.env"
  if $SUDO test -s "$ENV_FILE"; then
    say "Keeping existing $ENV_FILE"
    return
  fi
  say "Writing $ENV_FILE"
  SECRET="$(openssl rand -hex 32)"
  $SUDO tee "$ENV_FILE" >/dev/null <<EOF
# Generated by install.sh — do not commit this file.
PUBLIC_URL=$PUBLIC_URL
GAMEDAY_SECRET=$SECRET
PORT=$PORT
EOF
  $SUDO chmod 600 "$ENV_FILE"
}

start_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    say "Installing Docker"
    if ! curl -fsSL https://get.docker.com | $SUDO sh; then
      die "Docker could not be installed (in an unprivileged LXC you must enable Features → nesting,
or run: ./install.sh --native)"
    fi
  fi
  $SUDO docker compose version >/dev/null 2>&1 || die "docker compose v2 is missing"
  say "Building and starting the container"
  ( cd "$DIR" && $SUDO docker compose up -d --build --remove-orphans )
}

start_native() {
  if ! command -v node >/dev/null 2>&1 || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]; then
    say "Installing Node.js 22"
    curl -fsSL https://deb.nodesource.com/setup_22.x | $SUDO bash -
    install_pkgs nodejs
  fi
  say "Installing dependencies"
  ( cd "$DIR" && $SUDO npm ci --omit=dev && $SUDO mkdir -p data )

  manual_run() {
    say "Start it manually with:"
    printf '  cd %s && set -a && . ./.env && set +a && npm start\n' "$DIR"
  }

  if ! command -v systemctl >/dev/null 2>&1 || [ ! -d /run/systemd/system ]; then
    manual_run
    return
  fi

  say "Installing systemd service $APP"
  if ! $SUDO tee "/etc/systemd/system/$APP.service" >/dev/null <<EOF
[Unit]
Description=GameDay (College Football & UFC addon)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$DIR
EnvironmentFile=$DIR/.env
ExecStart=$(command -v node) src/server.js
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  then
    manual_run
    return
  fi
  $SUDO systemctl daemon-reload
  $SUDO systemctl enable --now "$APP"
  $SUDO systemctl restart "$APP"
}

install_pkgs
checkout_source
write_env

if [ "$MODE" = "auto" ]; then
  if command -v docker >/dev/null 2>&1; then MODE="docker"; else MODE="native"; fi
fi

printf '%s\n' "$MODE" > "$DIR/.gameday-mode"   # remembered by the Proxmox installer's --update

if [ "$MODE" = "docker" ]; then start_docker; else start_native; fi

IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
say "Done"
cat <<EOF
  Local:   http://${IP:-localhost}:$PORT/
  ${PUBLIC_URL:+Public:  $PUBLIC_URL/}
  Logs:    $([ "$MODE" = "docker" ] && echo "docker logs -f $APP" || echo "journalctl -u $APP -f")
  Update:  ./install.sh   (same flags again)
  Remove:  $([ "$MODE" = "docker" ] && echo "cd $DIR && docker compose down" || echo "systemctl disable --now $APP")

Open the local URL, enter your Xtream IPTV login (optional), pick sources, copy the install
link into Nuvio -> Settings -> Addons.
EOF
